const langs = ['en', 'ko', 'vi', 'zh'];

langs.forEach(function(lang) {
  if (!patches[lang]) return;
  const locale = loadLocale(lang);
  const langPatches = patches[lang];

  Object.keys(langPatches).forEach(function(section) {
    if (!locale[section]) {
      locale[section] = {};
    }
    const sectionPatch = langPatches[section];
    Object.keys(sectionPatch).forEach(function(key) {
      if (locale[section][key] === undefined) {
        locale[section][key] = sectionPatch[key];
      }
    });
  });

  saveLocale(lang, locale);
});

